use pest::iterators::{Pair, Pairs};

use crate::{directory::DirFunc};
use crate::{quadruples::Quadruples};
use crate::constants::{ASSIGN, DIV, ENTERO_TYPE, EQUAL, FLOTANTE_TYPE, GLOBAL, LESS, LITERAL_TYPE, MORE, MULTP, NOT_EQUAL, NULA_TYPE, PARENTHESIS, PLUS, SUBS};

use pest::Parser;
use pest_derive::Parser;

#[derive(Parser)]
#[grammar = "compiler_rules.pest"]
pub struct CSVParser;

pub struct Compiler {
    pub directory : DirFunc,
    pub quads : Quadruples,
}

impl Compiler {
    /// Main function in charge of compiling the whole program step by step
    pub fn compile_program(&mut self, program : &str) -> Result<(), String> {
        let nodes = CSVParser::parse(Rule::PROGRAM, program)
            .map_err(|e| format!("Syntax error: {}", e))?; // ! AI Claude helped me on how to throw syntax error when the parsing fails
        
        self.create_instructions(nodes)?;
        Ok(())
    }

    /// This function in charge of creating an instance when calling ::new()
    pub fn new() -> Self {
        Compiler {
            directory : DirFunc::new(),
            quads : Quadruples::new(),
        }
    }

    /// This function is in charge of created directory of functions and their variables
    
    fn create_instructions(&mut self, nodes : Pairs<Rule>) -> Result<(), String> {
        // ! The AI Claude was prompted to help me understand how to traverse the tree generated by Pest, which is using '.into_inner()'
        
        //* Inside the PROGRAM rule */
        self.directory.create_function(GLOBAL, NULA_TYPE)?; // Creates global function
        //* Reading from the top node PROGRAM */
        for node in nodes { // Returns the single PROGRAM that gives Pairs<Rule>
            for program_child in node.into_inner() {
                match program_child.as_rule() {
                    Rule::VARS => {
                        //* Process variables */
                        self.handle_vars(program_child, GLOBAL)?; // Pass VARS? to the next function to process MULT_VARS. In scope global
                    },
                    Rule::FUNCS => {
                        //* Process function by passing the function match */
                        self.handle_function(program_child)?;
                    },
                    Rule::BODY => {
                        //* Process the body by going to its child and passing 'ESTATUTO' */
                        // Set the current scope and tell where does the current function starts.
                        self.quads.set_scope_to(GLOBAL);
                        let starting_point = self.quads.quads.len();
                        self.directory.set_function_starting_point(&self.quads.get_scope(), starting_point)?;
                        self.handle_body(program_child)?;

                        // Need to update the global scope temporal counts
                        let (temp_int_count, temp_float_count) = self.quads.get_temporal_counts();
                        self.directory.set_temporal_count(self.quads.get_scope(), temp_int_count, temp_float_count)?;
                    }
                    _ => { }
                }
            }
        }

        self.quads.push_end();
        Ok(())
    }

    //* **** The next functions help traverse the tree and generate the quadruples */
    /// Process the body
    fn handle_body(&mut self, body : Pair<Rule>) -> Result<(), String> {
        // Handle body
        for body_child in body.into_inner() {
            match body_child.as_rule() {
                Rule::ESTATUTO => {
                    self.handle_statute(body_child)?;
                },
                _ => {}
            }
        }
        Ok(())
    }

    /// Processes the 'ESTATUTO' which are the different types of lines that exist in the program
    fn handle_statute(&mut self, statute : Pair<Rule>) -> Result<(), String> {
        //* Iterate over all the different types of statutes */
        for statute_child in statute.into_inner() {
            match statute_child.as_rule() {
                Rule::ASIGNA => {
                    self.handle_assign(statute_child)?;
                },
                Rule::CONDICION => {
                    // Handle rule: CONDICION = {"si" ~ "(" ~ EXPRESION ~ ")" ~ BODY ~ ("sino" ~ BODY)? ~ ";"}
                    self.handle_condition(statute_child)?;
                },
                Rule::CICLO => {
                    //* Handle rule: CICLO = {"mientras" ~ "(" ~ EXPRESION ~ ")" ~ "haz" ~ BODY ~ ";"} */
                    let mut cicle_children = statute_child.into_inner();

                    self.quads.push_jump(); // Save in the jump stack that in here starts the while. To save where the EXPRESION starts
                    let expression = cicle_children.next().unwrap();
                    self.handle_expression(expression)?;
                    self.quads.add_gotof(); // Create a gotoF with the last var of the stack, and saves it in the jump
                    let body = cicle_children.next().unwrap();
                    self.handle_body(body)?;
                    self.quads.add_goto_while(); // Handles updating the gotoF and adding the goto
                },
                Rule::CALL => {
                    // Handle rule: CALL = { ID ~ "(" ~  (EXPRESION ~ ("," ~ EXPRESION)* )? ~  ")" }
                    self.handle_call(statute_child, true)?;
                },
                Rule::IMPRIME => {
                    //* Handle rule: IMPRIME = {"escribe" ~ "(" ~  PRINT_STATEMENT ~ ("," ~ PRINT_STATEMENT)* ~ ")" ~ ";"} */
                    for print_statement in statute_child.into_inner() {
                        self.handle_print_statement(print_statement)?;
                    }
                },
                Rule::ESTATUTO => {
                    self.handle_statute(statute_child)?;
                },
                _ => {}
            }
        }
        Ok(())
    }

    /// Handle rule: CALL = { ID ~ "(" ~  (EXPRESION ~ ("," ~ EXPRESION)* )? ~  ")" }
    pub fn handle_call(&mut self, call_statement : Pair<Rule>, is_statement : bool) -> Result<(), String> {
        let mut id : &str = "";
        let mut param_counter : usize = 1;

        for call_child in call_statement.into_inner() {
            match call_child.as_rule() {
                Rule::ID => {
                    id = call_child.as_str();

                    if !self.directory.function_exists(id) {
                        return Err(format!("Sintax error: Invalid call, function doesn't exist"));
                    }

                    self.quads.create_era(id);
                },
                Rule::EXPRESION => {
                    self.handle_expression(call_child)?;
                    let parameters = &self.directory.functions.get(id).unwrap().parameters;
                    self.quads.create_param(param_counter, parameters)?; // pass vector of parameters of function
                    param_counter += 1; // Update the param counter that is being saved
                }
                _ => {}
            }
        }
        //* After handling all the expressions, generate the GOSUB */
        self.quads.create_gosub(id);


        if let Ok(function_type) = self.directory.get_var_type_of(GLOBAL, id) {
            // Se checa que el call no venga de un statement, porque si si entonces no se guarda el valor en la variable global
            if !is_statement {
                let return_addr = self.directory.get_var_address_of(GLOBAL, id)?;
                self.quads.push_function_temp(&return_addr, &function_type)?;
            }
        } else if !is_statement {
            return Err(format!("Error: cannot use void function '{}' in an expression", id));
        }

        // Check if the parameters passed match what the function was expecting
        let expected = self.directory.functions.get(id).unwrap().parameters.len();        
        if param_counter - 1 != expected {
            return Err(format!("Error: function '{}' expects {} args, got {}", id, expected, param_counter - 1));
        }
        Ok(())
    }

    /// Handle rule: PRINT_STATEMENT = {EXPRESION | LETRERO}
    pub fn handle_print_statement(&mut self, print_statement : Pair<Rule>) -> Result<(), String>{
        let statement = print_statement.into_inner().next().unwrap(); // Get inside the print statement
        match statement.as_rule() {
            Rule::EXPRESION => {
                self.handle_expression(statement)?;
                self.quads.generate_print_expr();
            },
            Rule::LETRERO => {
                let address = self.directory.save_constant(LITERAL_TYPE, statement.as_str())?;
                
                self.quads.generate_print_litr(&address.to_string());
            },
            _ => {},
        }
        Ok(())
    }

    /// Handle rule: CONDICION = {"si" ~ "(" ~ EXPRESION ~ ")" ~ BODY ~ ("sino" ~ BODY)? ~ ";"}
    pub fn handle_condition(&mut self, condition : Pair<Rule>) -> Result<(), String> {
        let mut condition_children = condition.into_inner();

        let expression = condition_children.next().unwrap();
        self.handle_expression(expression)?;
        self.quads.add_gotof(); // After checking expression, add the false that needs to be checked

        // Processes the body
        let body = condition_children.next().unwrap();
        self.handle_body(body)?;

        // Check if there is an else body
        match condition_children.next() {
            Some(else_body) => {
                self.quads.add_goto_if();
                self.handle_body(else_body)?; // Process the body inside

            },
            None => { // There is no 'ELSE' like statement}  
            }
        }
        self.quads.update_gotox(); // Process the goto or gotoF. Depending on previous match
        Ok(())
    }

    /// Handle rule: ASIGNA = { ID ~ "=" ~ EXPRESION ~ ";" }
    /// Handle assigning statute to add them in the quadruples
    pub fn handle_assign(&mut self, assign : Pair<Rule>) -> Result<(), String> {
        for assing_child in assign.into_inner() {
            match assing_child.as_rule() {
                Rule::ID => {
                    // Save the assign in the stack
                    let var_name = assing_child.as_str();
                    let var_type = self.directory.get_var_type_of(self.quads.get_scope(), var_name)?;

                    // Get the address of the variable
                    let address = self.directory.get_var_address_of(self.quads.get_scope(), var_name)?;

                    self.quads.push_var(address, var_type);

                    // Push the assign operator
                    self.quads.push_op(ASSIGN.to_string());
                },
                Rule::EXPRESION => {
                    self.handle_expression(assing_child)?;
                },
                _ => {},
            }
        }

        // Quadruple last operator must be '='
        self.quads.resolve()?;
        Ok(())
    }

    /// Handle rule: EXPRESION = { EXPR ~ (OPERATOR ~ EXPR)? }
    /// Handle expressions handle the *,/,+,-,etc
    pub fn handle_expression(&mut self, expression : Pair<Rule>) -> Result<(), String> {
        //* Iterate over all the expressions */
        for expression_child in expression.into_inner() {
            match expression_child.as_rule() {
                Rule::EXPR => {
                    self.handle_expr(expression_child)?;
                },
                Rule::OPERATOR => {
                    //* Add to the stack a logic operator */
                    self.quads.push_op(expression_child.as_str().to_string());
                },
                _ => {},
            }
        }

        //* Flush any remaining logic operators after processing */
        while let Some(top) = self.quads.stack_op_last() {
            if top == LESS || top == MORE || top == EQUAL || top == NOT_EQUAL {
                self.quads.resolve()?;
            } else { break; }
        }

        Ok(())
    }

    /// Handle the rule: EXPR = { TERM ~ (ARITH_OP ~ TERM)* }
    fn handle_expr(&mut self, expr : Pair<Rule>) -> Result<(), String> {
        for child in expr.into_inner() {
            match child.as_rule() {
                Rule::TERM => {
                    self.handle_term(child)?;
                },
                Rule::ARITH_OP => {
                    //* Before adding the next '+' or '-', resolve the pending ones */
                    if let Some(top) = self.quads.stack_op_last() {
                        if top == PLUS || top == SUBS {
                            self.quads.resolve()?;
                        }
                    }

                    self.quads.push_op(child.as_str().to_string());
                },
                _ => {},
            }
        }
        //* Flush any remaining ARITH_OP operators after processing */
        while let Some(top) = self.quads.stack_op_last() {
            if top == PLUS || top == SUBS {
                self.quads.resolve()?;
            } else { break; }
        }
        Ok(())
    }

    /// Handle the rule: TERM = { FACTOR ~ ( MULT_OP ~ FACTOR)* }
    fn handle_term(&mut self, term : Pair<Rule>) -> Result<(), String> {
        for child in term.into_inner() {
            match child.as_rule() {
                Rule::FACTOR => {
                    self.handle_factor(child)?;
                },
                Rule::MULT_OP => {
                    //* Before adding the next MULT_OP, resolve pending ones */
                    if let Some(top) = self.quads.stack_op_last() {
                        if top == MULTP || top == DIV {
                            self.quads.resolve()?;
                        }
                    }

                    self.quads.push_op(child.as_str().to_string());

                },
                _ => {}
            }
        }
        //* Flush any remaining MULT operators after processing */
        while let Some(top) = self.quads.stack_op_last() {
            if top == MULTP || top == DIV {
                self.quads.resolve()?;
            } else { break; }
        }
        Ok(())
    }

    /// Handle the rule: FACTOR = { SINGLE_EXPR | CALL | SINGLE_FACTOR }
    fn handle_factor(&mut self, factor : Pair<Rule>) -> Result<(), String> {
        let inner = factor.into_inner().next().unwrap(); // Get the first child
        match inner.as_rule() {
            Rule::SINGLE_EXPR => {
                //* SINGLE_EXPR = { "(" ~ EXPRESION ~ ")" } */
                // Push a fake bottom so inner flush loops don't consume outer operators
                self.quads.push_op(PARENTHESIS.to_string());
                let expression = inner.into_inner().next().unwrap();
                self.handle_expression(expression)?;
                self.quads.pop_op(); // Remove the fake bottom after expression resolves
            },
            Rule::CALL => {
                // Handle rule: CALL = { ID ~ "(" ~  (EXPRESION ~ ("," ~ EXPRESION)* )? ~  ")" }
                // Push a fake bottom so inner flush loops don't consume outer operators
                self.quads.push_op(PARENTHESIS.to_string());
                self.handle_call(inner, false)?;
                self.quads.pop_op(); // Remove the fake bottom after expression resolves
            },
            Rule::SINGLE_FACTOR => {
                // Handle rule: Handles rule: SINGLE_FACTOR = { ARITH_OP? ~ (ID | CTE )}
                // Process single factor, and adds variable to stack
                let single_factor = inner.into_inner();
                self.process_single_factor(single_factor)?;
            },
            _ => {},
        }
        Ok(())
    }

    /// Handles rule: SINGLE_FACTOR = { ARITH_OP? ~ (ID | CTE )}
    /// After getting single factor, gets if it has a sign, gets if is ENTERO or FLOTANTE, and gets if is a CTE or ID
    /// Adds variable to stack 
    fn process_single_factor(&mut self, mut single_factor : Pairs<Rule>) -> Result<(), String> {
        let mut term = single_factor.next().unwrap();
        let mut sign : &str = "";
        // Handle when the ID/CTE has a sign before it
        if term.as_rule() == Rule::ARITH_OP {
            sign = term.as_str(); // get sign as string
            term = single_factor.next().unwrap(); // get the ID or CTE
        }

        // Get the type of the CTE/ID using term (which right now is the name of the ID/CTE)
        match term.as_rule() {
            Rule::ID => {
                let var_type = self.directory.get_var_type_of(self.quads.get_scope(), term.as_str())?;

                let address = self.directory.get_var_address_of(self.quads.get_scope(), term.as_str())?;

                if sign == "-" {
                    // If a minus sign, need to emit a quad that performs that opeartion
                    let zero_addrs = self.directory.save_constant(ENTERO_TYPE, "0")?;

                    // Generate a quad that creates a temp variable with negative of the ID
                    self.quads.push_var(zero_addrs.to_string(), ENTERO_TYPE.to_string());
                    self.quads.push_var(address, var_type);
                    self.quads.push_op(SUBS.to_string());
                    self.quads.resolve()?; // leave on the stack a negated variable
                } else {
                    // If '+' don't do anything, just add the var
                    self.quads.push_var(address, var_type);
                }

            },
            Rule::CTE => {
                let var_name = format!("{}{}", sign, term.as_str());
                let cte_inner = term.into_inner().next().unwrap(); // Go to next child inside CTE which is either cte_entero or cte_flotante
                
                let var_type = match cte_inner.as_rule() {
                    Rule::cte_ent => ENTERO_TYPE.to_string(),
                    Rule::cte_flot => FLOTANTE_TYPE.to_string(),
                    _ => return Err(format!("Invalid constant")),
                };

                // Save and get the address of the constant created
                let address = self.directory.save_constant(&var_type, &var_name)?;
                self.quads.push_var(address.to_string(), var_type);
            },
            _ => {},
        }
        Ok(())
    }

    /// Handle rule: FUNCS = { FUNC_TYPE ~ ID ~ "(" ~ PARAMETERS? ~ ")" ~ "{" ~ VARS? ~ BODY ~ RETURN? ~ "}" ~ ";" }
    /// Processes the functions processes
    fn handle_function(&mut self, function : Pair<Rule>) -> Result<(), String> {
        //* Iterate over function statements, and processes its type and its variables */
        let mut funct_type : &str = "";
        let mut function_name : &str = "";

        for func_child in function.into_inner() {
            match func_child.as_rule() {
                Rule::FUNC_TYPE => {
                    funct_type = func_child.as_str();
                },
                Rule::ID => {
                    function_name = func_child.as_str();
                    self.directory.create_function(function_name, funct_type)?; // create the function in directory
                    self.quads.set_scope_to(function_name);

                    // Need to save a variable in global that will store the return of this function
                }
                Rule::PARAMETERS => {
                    //* Process each SINGLE_VAR that exists in parameters */
                    self.process_params(func_child)?;
                },
                Rule::VARS => {
                    self.handle_vars(func_child, function_name)?;
                },
                Rule::BODY => {
                    // Se crea la function como una variable global
                    if funct_type != NULA_TYPE {
                        self.directory.add_variable_to_function(GLOBAL, function_name, funct_type)?; // Add the function as a variable in global only if it has a return type
                    }

                    // Before handling body, tell where does the function start
                    // Every time handle the body, need to set the starting point of the current function in the diretory
                    let starting_point = self.quads.quads.len();
                    self.directory.set_function_starting_point(&self.quads.get_scope(), starting_point)?;
                    self.handle_body(func_child)?;
                },
                Rule::RETURN => {
                    // Handle rule: RETURN = { "return" ~ EXPRESION ~ ";"}

                    // Throw an error if the function is NULA_TYPE
                    if funct_type == NULA_TYPE {
                        return Err(format!("Syntax error: cannot have a return statement in a 'nula' function"))
                    }

                    // Se maneja la expresion y se crea el valor de retorno
                    let expression = func_child.into_inner().next().unwrap();
                    self.handle_expression(expression)?;

                    if let Ok(function_address) = self.directory.get_var_address_of(GLOBAL, function_name) {   
                        self.quads.create_return(funct_type, &function_address)?;
                    } else {
                        return Err(format!("Function doesn't exist"));
                    }
                },
                _ => {},
            }
        }
        
        // Need to update the function temporal counts
        let (temp_int_count, temp_float_count) = self.quads.get_temporal_counts();
        self.directory.set_temporal_count(self.quads.get_scope(), temp_int_count, temp_float_count)?;
        self.quads.push_end_f();
        Ok(())
    }
    
    /// Handle the rule: PARAMETERS = { SINGLE_VARS ~ ("," ~ SINGLE_VARS)* }
    /// Process the parameters of the function
    fn process_params(&mut self, params : Pair<Rule>) -> Result<(), String> {
        //* Process each SINGLE_VAR that exists in parameters */
        for variable in params.into_inner() {
            match variable.as_rule() {
                Rule::SINGLE_VARS => {
                    //* Traverse for each variable, its ID and TYPE  */
                    // Handle: SINGLE_VARS = { ID ~ ":" ~ TYPE}
                    let mut children = variable.into_inner();
                    let var_name = children.next().unwrap().as_str();
                    let var_type = children.next().unwrap().as_str();

                    self.directory.add_variable_to_function(&self.quads.get_scope(), var_name, var_type)?; // add variable to the variable directory

                    self.directory.add_param_to_function(&self.quads.get_scope(), var_type)?; // Add parameters type to the function
                }
                _ => {}
            }
        }
        Ok(())
    }

    /// Processes this single argument: MULT_VARS = {ID ~ ("," ~ ID)* ~ ":" ~ TYPE ~ ";"}
    fn handle_vars(&mut self, vars : Pair<Rule>, func_name : &str) -> Result<(), String> {
        for mult_var in vars.into_inner() {
            let mut ids : Vec<&str> = Vec::new();
            let mut var_type : &str = "";

            //* Iterate over every statement of MULT_VARS */
            for variables in mult_var.into_inner() {
                match variables.as_rule() {
                    Rule::ID => { ids.push(variables.as_str());},
                    Rule::TYPE => { var_type = variables.as_str()},
                    _ => { }
                }
            }
            
            for id in ids {
                self.directory.add_variable_to_function(func_name, id, var_type)?;
            }
        }
        Ok(())
    }
}


